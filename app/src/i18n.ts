function applyLanguageMode(language: string | undefined) {
  const locale = language?.startsWith("my") ? "my" : "en";
  const root = document.documentElement;
  root.lang = locale;
  root.dataset.locale = locale;
}

i18n.on("languageChanged", applyLanguageMode);

void i18n.use(initReactI18next).init({
  resources,
  lng: window.localStorage.getItem("archer.language") ?? "en",
  fallbackLng: "en",
  supportedLngs: ["en", "my"],
  interpolation: { escapeValue: false }
}).then(() => applyLanguageMode(i18n.resolvedLanguage ?? i18n.language));

i18n.on("languageChanged", (language) => window.localStorage.setItem("archer.language", language));

export default i18n;
